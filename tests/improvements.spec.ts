import { expect, test } from '@playwright/test';
import { demoUser, seedCreators, seedPosts } from '../lib/seed';

test('post formats and ordering preserve useful search state through sharing and reloads', async ({ page }) => {
  await page.goto('/?demo=1');
  await expect(page.locator('.post-card')).toHaveCount(seedPosts.length);
  const formats = page.getByRole('group', { name: 'Post format', exact: true });
  await formats.getByRole('button', { name: 'Videos', exact: true }).click();
  const videos = seedPosts.filter(post => post.mediaType === 'video');
  await expect(page.locator('.post-card')).toHaveCount(videos.length);
  await page.getByRole('combobox', { name: 'Sort posts', exact: true }).selectOption('newest');
  const newest = [...videos].sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
  await expect(page.locator('.post-card .post-title').first()).toHaveText(newest[0].title);
  expect(new URL(page.url()).searchParams.get('media')).toBe('video');
  expect(new URL(page.url()).searchParams.get('sort')).toBe('newest');
  await page.locator('.post-card .post-title').first().click();
  await expect(page.getByRole('dialog', { name: newest[0].title, exact: true })).toBeVisible();
  expect(new URL(page.url()).searchParams.get('media')).toBe('video');
  expect(new URL(page.url()).searchParams.get('sort')).toBe('newest');
  await page.getByRole('dialog', { name: newest[0].title, exact: true }).getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.reload();
  await expect(page.locator('.post-card')).toHaveCount(videos.length);
  await expect(page.getByRole('combobox', { name: 'Sort posts', exact: true })).toHaveValue('newest');
  await expect(formats.getByRole('button', { name: 'Videos', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await formats.getByRole('button', { name: 'Photos', exact: true }).click();
  await expect(page.locator('.post-card')).toHaveCount(seedPosts.filter(post => post.mediaType === 'image').length);
  await page.getByRole('combobox', { name: 'Sort posts', exact: true }).selectOption('liked');
  const liked = [...seedPosts.filter(post => post.mediaType === 'image')].sort((a, b) => b.likes - a.likes);
  await expect(page.locator('.post-card .post-title').first()).toHaveText(liked[0].title);
  await formats.getByRole('button', { name: 'All posts', exact: true }).click();
  await expect(page.locator('.post-card')).toHaveCount(seedPosts.length);
  expect(new URL(page.url()).searchParams.has('media')).toBe(false);
  await page.getByRole('button', { name: 'Food', exact: true }).click();
  await expect(page.locator('.post-card')).toHaveCount(seedPosts.filter(post => post.category === 'Food').length);
  expect(new URL(page.url()).searchParams.get('category')).toBe('Food');
  await page.getByRole('button', { name: 'Travel', exact: true }).click();
  await expect(page.locator('.post-card')).toHaveCount(seedPosts.filter(post => post.category === 'Travel').length);
  await page.goBack();
  await expect(page.getByRole('button', { name: 'Food', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.locator('.post-card')).toHaveCount(seedPosts.filter(post => post.category === 'Food').length);
});

test('browser history never displays personal saved posts on another creator profile', async ({ page }) => {
  const creator = seedCreators.find(person => person.id !== demoUser.id)!;
  const otherPosts = seedPosts.filter(post => post.creatorId === creator.id);
  await page.goto('/?demo=1&view=profile');
  await expect(page.getByRole('heading', { name: demoUser.name, exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Saved', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Saved', exact: true })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Explore', exact: true }).click();
  await page.locator('.creator-chip').filter({ hasText: creator.name }).getByRole('button', { name: `View ${creator.name} profile`, exact: true }).click();
  await expect(page.getByRole('heading', { name: creator.name, exact: true })).toBeVisible();
  await page.goBack();
  await page.goBack();
  await expect(page.getByRole('heading', { name: demoUser.name, exact: true })).toBeVisible();
  await page.getByRole('tab', { name: 'Saved', exact: true }).click();
  await page.goForward();
  await page.goForward();
  await expect(page.getByRole('heading', { name: creator.name, exact: true })).toBeVisible();
  await expect(page.getByRole('tab', { name: 'Saved', exact: true })).toHaveCount(0);
  await expect(page.locator('.post-card')).toHaveCount(otherPosts.length);
  await expect(page.locator('.post-card .post-title')).toHaveText(otherPosts.map(post => post.title));
});
